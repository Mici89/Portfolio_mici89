CREATE TABLE DISPATCH_TASK (
  TASK_ID NUMBER PRIMARY KEY, CC VARCHAR2(20), LINE_CD VARCHAR2(16), VEHICLE_ID NUMBER,
  DRIVER_ID NUMBER, PLAN_ST TIMESTAMP, ACT_ST TIMESTAMP, PLAN_ET TIMESTAMP, ACT_ET TIMESTAMP,
  ZT VARCHAR2(8), LOAD_RATE NUMBER(5,2), C01 VARCHAR2(100),
  CONSTRAINT FK_TASK_V FOREIGN KEY (VEHICLE_ID) REFERENCES VEHICLE(VEHICLE_ID),
  CONSTRAINT FK_TASK_D FOREIGN KEY (DRIVER_ID) REFERENCES DRIVER(ID)
);

CREATE TABLE TASK_WAYBILL (
  TASK_ID NUMBER NOT NULL, YD_H VARCHAR2(24) NOT NULL, SX NUMBER(6), LOAD_TM TIMESTAMP,
  UNLOAD_TM TIMESTAMP, PRIMARY KEY(TASK_ID, YD_H),
