CREATE TABLE PACKAGE_ITEM (
  PACKAGE_ID NUMBER PRIMARY KEY, PACKAGE_NO VARCHAR2(28) UNIQUE NOT NULL,
  WAYBILL_NO VARCHAR2(24), SEQ_NO NUMBER(5), LENGTH_CM NUMBER(8,2), WIDTH_CM NUMBER(8,2),
  HEIGHT_CM NUMBER(8,2), WEIGHT_KG NUMBER(10,2), BARCODE_STATUS VARCHAR2(12), CREATED_TIME TIMESTAMP
