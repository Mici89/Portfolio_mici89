CREATE TABLE REGION_DICT (
  REGION_CODE VARCHAR2(12) PRIMARY KEY, REGION_NAME VARCHAR2(60) NOT NULL,
  PARENT_CODE VARCHAR2(12), LV NUMBER(2), C01 VARCHAR2(30)
);
COMMENT ON TABLE REGION_DICT IS '行政区划及运营区域字典';
COMMENT ON COLUMN REGION_DICT.C01 IS '历史系统保留属性，可能为空';

CREATE TABLE BRANCH (
  BRANCH_ID NUMBER PRIMARY KEY, BRANCH_CODE VARCHAR2(12) UNIQUE NOT NULL,
  BRANCH_NAME VARCHAR2(100) NOT NULL, REGION_CODE VARCHAR2(12), ADDRESS VARCHAR2(200),
  MANAGER_NAME VARCHAR2(40), PHONE VARCHAR2(30), ACTIVE_FLAG CHAR(1) DEFAULT 'Y', OPEN_DATE DATE,
  CONSTRAINT FK_BRANCH_REGION FOREIGN KEY (REGION_CODE) REFERENCES REGION_DICT(REGION_CODE)
);

CREATE TABLE CUSTOMER (
  CUSTOMER_ID NUMBER PRIMARY KEY, CUSTOMER_NO VARCHAR2(20) UNIQUE NOT NULL,
  CUSTOMER_NAME VARCHAR2(120) NOT NULL, CUSTOMER_TYPE VARCHAR2(12), CREDIT_LEVEL CHAR(1),
  CONTACT_NAME VARCHAR2(40), CONTACT_PHONE VARCHAR2(30), BILLING_CYCLE VARCHAR2(10),
  HOME_BRANCH_ID NUMBER, CREATED_AT TIMESTAMP, REMARK VARCHAR2(300),
  CONSTRAINT FK_CUST_BRANCH FOREIGN KEY (HOME_BRANCH_ID) REFERENCES BRANCH(BRANCH_ID)
);
COMMENT ON TABLE CUSTOMER IS '物流客户主数据';
COMMENT ON COLUMN CUSTOMER.CREDIT_LEVEL IS 'A-D，A为最高';

CREATE TABLE DRIVER (
  ID NUMBER PRIMARY KEY, XM VARCHAR2(40), SJ VARCHAR2(30), SFZ VARCHAR2(24),
  WD_DM VARCHAR2(12), ZT CHAR(1), RQ DATE, LIC_TYPE VARCHAR2(8)
);

CREATE TABLE VEHICLE (
  VEHICLE_ID NUMBER PRIMARY KEY, PLATE_NO VARCHAR2(16) UNIQUE NOT NULL,
  VEHICLE_TYPE VARCHAR2(20), CAPACITY_KG NUMBER(12,2), CAPACITY_M3 NUMBER(8,2),
  OWNER_TYPE CHAR(1), BRANCH_CODE VARCHAR2(12), STATUS_CODE VARCHAR2(10),
  PURCHASE_DATE DATE, NEXT_MAINT_DATE DATE
);

CREATE TABLE ROUTE_MASTER (
  ROUTE_ID NUMBER PRIMARY KEY, LINE_CD VARCHAR2(16) UNIQUE, ORIGIN_BRANCH_ID NUMBER,
  DEST_BRANCH_ID NUMBER, DIST_KM NUMBER(8,1), STD_HOURS NUMBER(6,1), ZT CHAR(1), C02 VARCHAR2(60),
  CONSTRAINT FK_ROUTE_O FOREIGN KEY (ORIGIN_BRANCH_ID) REFERENCES BRANCH(BRANCH_ID),
  CONSTRAINT FK_ROUTE_D FOREIGN KEY (DEST_BRANCH_ID) REFERENCES BRANCH(BRANCH_ID)
);

CREATE TABLE T_YD01 (
  ID NUMBER PRIMARY KEY, YD_H VARCHAR2(24) UNIQUE NOT NULL, KH_BH VARCHAR2(20),
  F_WD VARCHAR2(12), D_WD VARCHAR2(12), RQ DATE, SJ TIMESTAMP, ZL NUMBER(12,2),
  JS NUMBER(8), JE NUMBER(14,2), ZT VARCHAR2(8), YSFS VARCHAR2(8), C01 VARCHAR2(80),
  CREATED_BY VARCHAR2(30)
);
COMMENT ON COLUMN T_YD01.YD_H IS '运单号码';
